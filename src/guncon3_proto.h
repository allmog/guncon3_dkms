struct guncon3_state {
	gc3_u32 buttons;	/* GUNCON3_BTN_* | GUNCON3_STATUS_* */
	gc3_s16 x, y;		/* raw aim, as reported by the sensor */
	gc3_u16 z;		/* distance-related, unscaled */
	gc3_u8 ax, ay;		/* A-stick, 0..255, ~128 centre, 0 = left/up */
	gc3_u8 bx, by;		/* B-stick */
};

/*
 * Decrypt a 15-byte report into 13 payload bytes. Returns 0 on success,
 * -1 if the checksum does not match the key (e.g. the gun has not taken
 * our key yet, or the report is corrupt). @raw is not modified.
 */
static inline int guncon3_decrypt(const gc3_u8 *raw, const gc3_u8 *key,
				  gc3_u8 *payload)
{
	int a_sum, b_sum, key_offset, key_index, x, y;

	b_sum = ((raw[13] ^ raw[12]) + raw[11] + raw[10] - raw[9] - raw[8]) ^ raw[7];
	b_sum &= 0xFF;
	a_sum = (((raw[6] ^ b_sum) - raw[5] - raw[4]) ^ raw[3]) + raw[2] + raw[1] - raw[0];
	a_sum &= 0xFF;
	if (a_sum != key[7])
		return -1;

	key_offset = (((((key[1] ^ key[2]) - key[3] - key[4]) ^ key[5]) + key[6] - key[7])
		      ^ raw[14]) + 0x26;
	key_offset &= 0xFF;
	key_index = 4;

	for (x = 12; x >= 0; x--) {
		gc3_u8 byte = raw[x];

		for (y = 0; y < 3; y++) {
			gc3_u8 bkey, keyr;

			/*
			 * key_offset starts in 0..255 and drops 39 times,
			 * so the index stays within 26..319.
			 */
			key_offset--;
			bkey = guncon3_key_table[key_offset + 0x41];
			keyr = key[key_index];
			if (--key_index == 0)
				key_index = 7;

			switch (bkey & 3) {
			case 0:
				byte = byte - bkey - keyr;
				break;
			case 1:
				byte = byte + bkey + keyr;
				break;
			default:
				byte = byte ^ bkey ^ keyr;
				break;
			}
		}
		payload[x] = byte;
	}
	return 0;
}

static inline void guncon3_parse(const gc3_u8 *p, struct guncon3_state *st)
{
	st->buttons = (gc3_u32)p[2] << 16 | (gc3_u32)p[1] << 8 | p[0];
	st->x = (gc3_s16)(p[4] << 8 | p[3]);
	st->y = (gc3_s16)(p[6] << 8 | p[5]);
	st->z = (gc3_u16)(p[8] << 8 | p[7]);
	st->ax = p[9];
	st->ay = p[10];
	st->bx = p[11];
	st->by = p[12];
}

